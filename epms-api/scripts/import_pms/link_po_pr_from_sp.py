async def run(commit: bool) -> None:
    async with session_module.AsyncSessionLocal() as db:
        pos = (await db.execute(
            select(PurchaseOrder).where(
                PurchaseOrder.pr_id.is_(None),
                PurchaseOrder.number.in_(list(_MAP.keys())),
            ).order_by(PurchaseOrder.number)
        )).scalars().all()
        linked = 0
        unresolved = []
        for po in pos:
            prno = _MAP.get(po.number)
            pr = (await db.execute(
                select(PurchaseRequest).where(PurchaseRequest.number == prno)
            )).scalar_one_or_none()
            if pr is None:
                unresolved.append((po.number, prno))
                continue
            print(f"  {po.number} -> {pr.number}")
            if commit:
                po.pr_id = pr.id
                po.pr_number = pr.number
                po.type = pr.type
                po.created_by = pr.created_by or po.created_by
                if po.title == po.number:
                    po.title = pr.number
                if pr.po_id is None:
                    pr.po_id = po.id
                if pr.po_number != po.number:
                    pr.po_number = po.number
            linked += 1
        if unresolved:
            print(f"  {len(unresolved)} PO(s) whose mapped PR is NOT in the DB (left as-is):")
            for pon, prn in unresolved[:20]:
                print(f"    {pon} -> {prn} (PR missing)")
        if commit:
            await db.commit()
            print(f"APPLIED: linked {linked} PO(s) to their PR.")
        else:
            await db.rollback()
            print(f"DRY-RUN: would link {linked} PO(s). --commit to write.")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--commit", action="store_true")
    args = ap.parse_args()
    asyncio.run(run(commit=args.commit))
