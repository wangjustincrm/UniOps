"""Evidence about an open NC payable that the AP documents alone do not show.

Two findings, both read from what NC already holds, never stored:

**Settled by journal voucher.** Some old payables have no payment document at
all: finance cleared them with a GL voucher straight to the payable account,
and the only link is the invoice number typed into the voucher summary. For a
bill with no approved payment pointing at it, this looks for lines on a 2202*
account, for the same supplier, that move the payable the other way (a debit
against a bill, a credit against a credit note), whose summary mentions one of
the bill's invoice numbers. Measured 2026-10-20: 49 of 232 open, unpaid bills
that carry an invoice number have such a line.

**Same invoice in another currency.** NC can hold one supplier invoice twice:
a payable generated by a supply-chain settlement in CAD (trade type D1) and the
one finance keyed in the invoice's own currency and paid. Independent Can
Company's 2025-11-29 CAD bills (396,186.27, still open) repeat seven USD bills
that were all paid. Measured 2026-10-20: 12 open CAD bills, 1,790,521.22, all
D1, all dated 2025-11-29. Flagged, never netted: which of the two is real is
finance's call.

Invoice numbers are compared as tokens, not whole strings: NC users key several
invoices into one field ("9151970/1987/1992" = 9151970, 9151987, 9151992), so
an exact comparison of the field never matches the single-invoice bill.
"""
from __future__ import annotations

import re
from collections import defaultdict
from decimal import Decimal

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

AP_ACCOUNT_PREFIX = "2202"
# Shorter tokens ("2020", "6249") match unrelated text far too often.
MIN_TOKEN_LEN = 4
MAX_JV_PER_BILL = 5

_SPLIT = re.compile(r"[/,;&]")
_WS = re.compile(r"\s")


def invoice_tokens(invoice_no: str | None) -> list[str]:
    """The invoice numbers inside one NC invoice field, upper-cased.

    A shorter all-digit token after a longer one replaces that number's tail:
    "9151970/1987/1992" -> 9151970, 9151987, 9151992; "9152018/005" ->
    9152018, 9152005. Anything else stands as typed ("CR590-0"). A leading "#"
    is dropped.
    """
    s = _WS.sub("", (invoice_no or "").upper())
    out: list[str] = []
    base = None
    for t in (x for x in _SPLIT.split(s) if x):
        if base and t.isdigit() and len(t) < len(base):
            t = base[: len(base) - len(t)] + t
        elif t.isdigit():
            base = t
        t = t.lstrip("#")
        if len(t) >= MIN_TOKEN_LEN and t not in out:
            out.append(t)
    return out


def _mentions(summary_upper: str, token: str) -> bool:
    """`token` appears in the summary as a whole number, not inside a longer one."""
    return re.search(r"(?<![A-Z0-9])" + re.escape(token) + r"(?![A-Z0-9])",
                     summary_upper) is not None


def _effect(debit, credit) -> Decimal:
    """What a 2202 line did to the payable: debit reduces it."""
    return Decimal(debit or 0) - Decimal(credit or 0)


async def attach(db: AsyncSession, bills: list[dict], currency_of=lambda b: b["currency"]) -> None:
    """Add `jv_matches` and `other_currency` to each bill dict, in place.

    Each bill needs: bill_no, supplier_code, supplier_name, money_bal,
    `invoices` (from nc_ap_bill_invoices.invoices) and `payment_lines` (approved
    payment lines pointing at it). JV evidence is only looked for when
    payment_lines is 0 — a bill with a payment document is not the case this
    answers.
    """
    for b in bills:
        b["jv_matches"] = []
        b["other_currency"] = []
    if not bills:
        return
    tokens = {b["bill_no"]: [t for i in b["invoices"] for t in invoice_tokens(i["invoice_no"])]
              for b in bills}
    codes = sorted({b["supplier_code"] for b in bills if b.get("supplier_code")})
    # Trimmed on both sides: NC's voucher lines carry the partner name with a
    # trailing space on some lines ("CCIC Agri-Food Testing (North America)
    # Inc "), 1,506 of 50,129 payable-account lines at measurement.
    names = sorted({b["supplier_name"].strip() for b in bills
                    if b.get("supplier_name") and b.get("payment_lines", 0) == 0})

    if names:
        rows = (await db.execute(text(f"""
            select v.jv_number, v.voucher_date, v.source_subsystem,
                   trim(l.partner_name) as partner_name,
                   l.currency, l.orig_debit, l.orig_credit,
                   upper(concat_ws(' | ', l.summary, v.summary)) as summary,
                   coalesce(l.summary, v.summary) as summary_raw
              from journal_voucher_lines l
              join journal_vouchers v on v.id = l.jv_id
             where trim(l.partner_name) = any(:names)
               and l.account_code like '{AP_ACCOUNT_PREFIX}%'
               and (coalesce(l.orig_debit, 0) <> 0 or coalesce(l.orig_credit, 0) <> 0)
             order by v.voucher_date, v.jv_number
        """), {"names": names})).mappings().all()
        by_partner: dict[str, list] = defaultdict(list)
        for r in rows:
            by_partner[r["partner_name"]].append(r)
        for b in bills:
            if b.get("payment_lines", 0) != 0 or not tokens[b["bill_no"]]:
                continue
            bal = Decimal(b["money_bal"] or 0)
            if bal == 0:
                continue
            for r in by_partner.get((b.get("supplier_name") or "").strip(), []):
                eff = _effect(r["orig_debit"], r["orig_credit"])
                # Must move the payable the way that clears THIS bill. The
                # bill's own booking (a credit on a bill) is the other way.
                if eff == 0 or (eff > 0) != (bal > 0):
                    continue
                hit = next((t for t in tokens[b["bill_no"]] if _mentions(r["summary"], t)), None)
                if not hit:
                    continue
                b["jv_matches"].append({
                    "jv_number": r["jv_number"],
                    "voucher_date": r["voucher_date"].isoformat() if r["voucher_date"] else None,
                    "subsystem": r["source_subsystem"],
                    "currency": r["currency"],
                    "amount": str(eff),
                    "invoice_no": hit,
                    "summary": r["summary_raw"],
                    "amount_matches": abs(eff) == abs(bal),
                })
                if len(b["jv_matches"]) >= MAX_JV_PER_BILL:
                    break

    if codes:
        rows = (await db.execute(text("""
            select b.bill_no, b.currency, b.bill_date::date as bill_date, l.supplier_code,
                   l.invoice_no, l.money_cr, l.money_bal
              from nc_ap_bill_lines l
              join nc_ap_bills b on b.id = l.bill_id
             where b.bill_status = 1 and b.approve_status = 1
               and l.supplier_code = any(:codes)
               and l.invoice_no is not null
        """), {"codes": codes})).mappings().all()
        # Totals are per BILL (every line), whichever line carried the number.
        totals: dict[str, dict] = {}
        index: dict[tuple, set] = defaultdict(set)      # (supplier, token) -> bill_nos
        for r in rows:
            e = totals.setdefault(r["bill_no"], {
                "bill_no": r["bill_no"], "currency": r["currency"],
                "bill_date": r["bill_date"].isoformat() if r["bill_date"] else None,
                "money_cr": Decimal(0), "money_bal": Decimal(0)})
            e["money_cr"] += r["money_cr"] if r["money_cr"] is not None else 0
            e["money_bal"] += r["money_bal"] if r["money_bal"] is not None else 0
            for t in invoice_tokens(r["invoice_no"]):
                index[(r["supplier_code"], t)].add(r["bill_no"])
        for b in bills:
            ccy = currency_of(b)
            twins: dict[str, list] = {}
            for t in tokens[b["bill_no"]]:
                for other in index.get((b.get("supplier_code"), t), ()):
                    if other == b["bill_no"] or totals[other]["currency"] == ccy:
                        continue
                    shared = twins.setdefault(other, [])
                    if t not in shared:
                        shared.append(t)
            b["other_currency"] = [{**totals[o], "money_cr": str(totals[o]["money_cr"]),
                                    "money_bal": str(totals[o]["money_bal"]),
                                    "invoice_nos": twins[o]}
                                   for o in sorted(twins)]


async def unattributed_clearings(db: AsyncSession, supplier_code: str,
                                 supplier_name: str | None, currency: str,
                                 limit: int = 20) -> dict:
    """Payable-account clearings for this supplier that name NO invoice.

    The case that prompted it: CCIC Agri-Food Testing, 15 bills of 2025 with no
    payment document, all still open, and one GL voucher on 2025-12-30 —
    debit payable 292,798.92 / credit receivable, "Record CCIC AR & AP
    deducted" — that netted what CCIC owed us (rent, utilities) against what
    we owed CCIC. No invoice number in it, so nothing per bill can find it.

    Shown per supplier, beside the bills, for finance to compare — never
    applied to any bill. Kept narrow on purpose (measured 2026-10-20: 4
    suppliers, 11 lines, CCIC's voucher among them) by these rules:

    * only when the supplier has open, approved bills with no approved
      payment that finance has not set aside; nothing before the oldest of
      them (a clearing cannot settle a bill raised after it);
    * 2202* lines, same supplier (partner name, trimmed), same currency, not
      raised by the AP subsystem (payment documents have their own link);
    * moving the payable down (debit, or a negative credit);
    * pairs that cancel each other out across the supplier's whole history
      (an accrual and its reversal) are dropped;
    * a summary naming ANY invoice number on this supplier's bills, settled
      or not, is attributed already and is left out.
    """
    empty = {"since": None, "unpaid_bills": 0, "unpaid_open": "0",
             "lines": [], "total": "0"}
    if not supplier_name:
        return empty
    unpaid = (await db.execute(text("""
        select count(*) as bills, coalesce(sum(bal), 0) as open, min(bill_date) as since
          from (
            select b.bill_no, min(b.bill_date)::date as bill_date, sum(l.money_bal) as bal
              from nc_ap_bill_lines l
              join nc_ap_bills b on b.id = l.bill_id
             where l.supplier_code = :code and b.currency = :ccy
               and b.bill_status = 1 and b.approve_status = 1 and l.money_bal <> 0
               and not exists (select 1 from nc_ap_bill_dismissals d
                                where d.bill_no = b.bill_no and d.restored_at is null)
               and not exists (select 1 from nc_ap_payment_lines p
                                 join nc_ap_payments ph on ph.id = p.payment_id
                                where p.top_bill_id = b.nc_pk
                                  and ph.bill_status = 1 and ph.approve_status = 1)
             group by b.bill_no
            having sum(l.money_bal) > 0
          ) x
    """), {"code": supplier_code, "ccy": currency})).mappings().one()
    if not unpaid["bills"]:
        return empty

    known: set[str] = set()
    for (inv,) in (await db.execute(text("""
        select distinct invoice_no from nc_ap_bill_lines
         where supplier_code = :code and invoice_no is not null
    """), {"code": supplier_code})).all():
        known.update(invoice_tokens(inv))

    rows = (await db.execute(text(f"""
        select v.jv_number, v.voucher_date, v.source_subsystem,
               coalesce(l.orig_debit, 0) as debit, coalesce(l.orig_credit, 0) as credit,
               upper(concat_ws(' | ', l.summary, v.summary)) as summary,
               coalesce(l.summary, v.summary) as summary_raw
          from journal_voucher_lines l
          join journal_vouchers v on v.id = l.jv_id
         where trim(l.partner_name) = :name
           and l.account_code like '{AP_ACCOUNT_PREFIX}%'
           and l.currency = :ccy
           and (coalesce(l.orig_debit, 0) <> 0 or coalesce(l.orig_credit, 0) <> 0)
         order by v.voucher_date, v.jv_number
    """), {"name": supplier_name.strip(), "ccy": currency})).mappings().all()

    # Drop self-cancelling pairs: equal and opposite effect, matched greedily
    # in date order.
    effects = [_effect(r["debit"], r["credit"]) for r in rows]
    waiting: dict[Decimal, list[int]] = defaultdict(list)
    cancelled: set[int] = set()
    for i, e in enumerate(effects):
        if waiting.get(-e):
            cancelled.update((i, waiting[-e].pop(0)))
        else:
            waiting[e].append(i)

    since = unpaid["since"]
    lines = []
    for i, r in enumerate(rows):
        e = effects[i]
        if (i in cancelled or e <= 0 or r["source_subsystem"] == "AP"
                or r["voucher_date"] is None or r["voucher_date"] < since):
            continue
        if any(_mentions(r["summary"], t) for t in known):
            continue
        lines.append({
            "jv_number": r["jv_number"],
            "voucher_date": r["voucher_date"].isoformat(),
            "subsystem": r["source_subsystem"],
            "amount": str(e),
            "summary": r["summary_raw"],
        })
    return {
        "since": since.isoformat() if since else None,
        "unpaid_bills": int(unpaid["bills"]),
        "unpaid_open": str(unpaid["open"]),
        "lines": lines[-limit:],
        "total": str(sum((Decimal(x["amount"]) for x in lines), Decimal(0))),
    }
