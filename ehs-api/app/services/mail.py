"""Sending Safety's email, and keeping a copy of everything it sent.

Two things happen on every send and the second is the point. HSE asked that
"all emails sent and received by the system are automatically filed against the
corresponding record, forming an audit trail" — so a message is not fired off
and forgotten: it is written into `ehs_communications` attached to the incident,
action or document it is about. Three years later, "were they told?" has an
answer.

Sending is two steps on purpose. `queue()` writes the archive row inside the
caller's own transaction, so the record of "we told them" commits or rolls back
with the thing it is about — an incident that failed to save cannot leave
behind a note saying it was circulated. `deliver()` then does the network call
in the background with its own session, so a slow or dead mail server holds up
nobody's request.

A message that failed to leave is a row with no `sent_at`. That is the honest
record, and it is the case somebody asks about later; stamping the row only on
success would leave no trace of the attempt at all.

SMTP credentials come from `company_config`, the same row epms-api uses. Safety
sends its own mail rather than routing through epms-api — the messages are
Safety's, and an HTTP hop to another service to send them would add a failure
mode and return nothing.

Nothing here raises. A statutory deadline must not fail to escalate because a
mail server was down.
"""
from __future__ import annotations

import html
import logging
import uuid
from datetime import datetime, timezone
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from email.utils import make_msgid

from sqlalchemy import event, select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import Session

from app.core import background
from app.core.config import settings
from app.models.communication import Communication
from app.models.mirrors import CompanyConfig, User

logger = logging.getLogger(__name__)

# Recipients whose channel is one of these are skipped. `notification_channel`
# is NOT NULL with a server default in production, so it is read as the
# person's own choice and not fallen back over.
OPTED_OUT = {"none", "teams_only"}


async def _config(db: AsyncSession) -> CompanyConfig | None:
    return (await db.execute(select(CompanyConfig).limit(1))).scalar_one_or_none()


def _smtp(cfg: CompanyConfig | None) -> dict:
    """Company settings first, environment as the fallback."""
    return {
        "host": (cfg.smtp_host if cfg else None) or settings.SMTP_HOST,
        "port": (cfg.smtp_port if cfg else None) or settings.SMTP_PORT,
        "user": (cfg.smtp_user if cfg else None) or settings.SMTP_USER,
        "password": (cfg.smtp_password if cfg else None) or settings.SMTP_PASSWORD,
        "use_tls": (cfg.smtp_use_tls if cfg and cfg.smtp_use_tls is not None
                    else settings.SMTP_USE_TLS),
        "from_addr": (cfg.smtp_from if cfg else None) or settings.SMTP_FROM,
    }


def render(body: str, *, title: str, link: str | None = None,
           link_label: str = "Open it in Safety", links: dict[str, str] | None = None) -> str:
    """The one HTML shell every Safety email uses.

    Deliberately plain: these are read on a phone in a corridor, often by
    somebody who has thirty seconds. One heading, the text, one link.

    ★★ Everything interpolated is escaped first. Most of what reaches here was
    typed by somebody: an incident title, a description, a committee
    recommendation, a general comment. Unescaped, a person could write

        <a href="https://elsewhere/login">Your session expired — sign in</a>

    into a field and have this module send it, from the plant's own address,
    with the plant's own heading above it, to HSE. That is a phishing mail with
    our name on it, composed through a text box.

    Raised in review by uniops-9a while reading the new feedback screen. It was
    not introduced there — eleven callers pass user text into this — but a
    single free-text box made it reachable without first filing an incident.
    Fixed in the shell so all of them are fixed at once.

    The newline substitution happens *after* escaping, so line breaks still
    render while `<br>` typed by a person does not.
    """
    button = ""
    if link:
        # Generated by `module_link`, escaped anyway: an attribute built by
        # concatenation is not somewhere to make an exception.
        button = (
            f'<p style="margin:20px 0 0"><a href="{html.escape(link, quote=True)}" '
            'style="background:#0f766e;color:#fff;padding:10px 18px;border-radius:6px;'
            'text-decoration:none;font-weight:600;display:inline-block">'
            f'{html.escape(link_label)}</a></p>'
        )
    title = html.escape(title)
    safe_body = html.escape(body)
    # ★ UAT 13: "The incident and CAPA numbers are clickable." Record numbers
    # this module generated, and URLs it built, matched after escaping — so a
    # number somebody typed into a description is linked only if it is the
    # record's own, and nothing typed becomes markup.
    for text, url in (links or {}).items():
        if text:
            safe_body = safe_body.replace(
                html.escape(text),
                f'<a href="{html.escape(url, quote=True)}" style="color:#0f766e;font-weight:600">'
                f'{html.escape(text)}</a>')
    safe_body = safe_body.replace("\n", "<br>")
    return (
        '<div style="font-family:-apple-system,Segoe UI,Roboto,sans-serif;'
        'max-width:560px;color:#1f2937;line-height:1.5">'
        f'<h2 style="margin:0 0 12px;font-size:17px;color:#0f172a">{title}</h2>'
        f'<div style="font-size:14px">{safe_body}</div>'
        f'{button}'
        '<p style="margin:24px 0 0;font-size:12px;color:#6b7280">'
        'Sent by UniOps Safety. Replies to this address are not monitored yet.'
        '</p></div>'
    )


def module_link(path: str) -> str:
    """An absolute URL into the Safety front end."""
    return f"{settings.SAFETY_WEB_URL.rstrip('/')}{path}"


async def recipients(
    db: AsyncSession, user_ids: list[uuid.UUID | None]
) -> list[User]:
    """Active people with an address who have not opted out of email.

    Silently dropping an opted-out recipient is correct here: this is the
    module's second channel, not its only one. Everything that needs doing has
    a task in the inbox as well.
    """
    ids = [u for u in user_ids if u]
    if not ids:
        return []
    rows = (await db.execute(
        select(User).where(User.id.in_(ids), User.is_active.is_(True)))).scalars().all()
    return [u for u in rows
            if u.email and (u.notification_channel or "email_only") not in OPTED_OUT]


async def queue(
    db: AsyncSession,
    *,
    to: list[str],
    subject: str,
    body: str,
    doc_type: str | None = None,
    doc_id: uuid.UUID | None = None,
    template_key: str | None = None,
    link: str | None = None,
    link_label: str = "Open it in Safety",
    cc: list[str] | None = None,
    links: dict[str, str] | None = None,
) -> Communication | None:
    """File the message against its record and schedule the send.

    Runs in the caller's transaction. Returns the archive row, or None when
    there was nobody to send to.
    """
    to = [a for a in dict.fromkeys(a.strip() for a in to if a and a.strip())]
    if not to:
        return None
    return await _file(db, to=to, cc=cc, subject=subject, body=body,
                       body_html=render(body, title=subject, link=link, link_label=link_label,
                                        links=links),
                       doc_type=doc_type, doc_id=doc_id, template_key=template_key,
                       link=link, link_label=link_label)


# ★ Round 12, COM-03: the record's own number, so the log can be searched on
# it. One query per kind of record; a kind not here is filed without one.
DOC_NUMBER_SQL: dict[str, str] = {
    "ehs_inc": "select incident_no from ehs_incidents where id = :id",
    "ehs_act": "select action_no from ehs_actions where id = :id",
    "ehs_doc": "select doc_no from ehs_documents where id = :id",
    "ehs_crs": "select delivery_no from ehs_course_deliveries where id = :id",
    "ehs_tbt": ("select t.talk_no from ehs_tbt_deliveries d join ehs_toolbox_talks t "
                "on t.id = d.talk_id where d.id = :id"),
    "ehs_jhsc": ("select coalesce((select meeting_no from ehs_jhsc_meetings where id = :id),"
                 " (select m.meeting_no || ' #' || r.seq from ehs_jhsc_recommendations r"
                 "  join ehs_jhsc_meetings m on m.id = r.meeting_id where r.id = :id))"),
    "ehs_haz": "select hazard_no from ehs_hazards where id = :id",
    "ehs_ptw": "select permit_no from ehs_permits where id = :id",
    "ehs_sub": "select submission_no from ehs_form_submissions where id = :id",
}


async def _people_and_number(db: AsyncSession, to: list[str], doc_type, doc_id):
    from sqlalchemy import func, text
    ids = [str(i) for i in (await db.execute(select(User.id).where(
        func.lower(User.email).in_([a.lower() for a in to])))).scalars()]
    number = None
    sql = DOC_NUMBER_SQL.get(doc_type or "")
    if sql and doc_id:
        number = (await db.execute(text(sql), {"id": doc_id})).scalar()
    return ids, (str(number)[:60] if number else None)


async def _file(db: AsyncSession, *, to: list[str], cc: list[str] | None, subject: str,
                body: str, body_html: str, doc_type, doc_id, template_key,
                link: str | None, link_label: str | None,
                resend_of: uuid.UUID | None = None,
                resent_by_name: str | None = None) -> Communication:
    """Write the archive row and hold its send until the caller commits."""
    to_user_ids, doc_number = await _people_and_number(db, to, doc_type, doc_id)

    from_addr = _smtp(await _config(db))["from_addr"] or ""
    record = Communication(
        id=uuid.uuid4(),
        doc_type=doc_type, doc_id=doc_id,
        direction="out",
        from_addr=from_addr,
        to_addrs=list(to), cc_addrs=list(cc or []),
        subject=subject, body_text=body, body_html=body_html,
        # Set now and sent as the header, so an inbound reply's In-Reply-To can
        # be matched back to this row when the inbound channel is built.
        message_id=make_msgid(domain="safety.uniops"),
        template_key=template_key,
        to_user_ids=to_user_ids, doc_number=doc_number,
        link=link[:500] if link else None, link_label=link_label,
        resend_of=resend_of, resent_by_name=resent_by_name,
    )
    db.add(record)
    await db.flush()

    # ★ Round 10, TC-04: sent only once the caller's transaction commits.
    #
    # It was spawned here, straight after the flush. `deliver` reads the row in
    # a session of its own, which cannot see a row not yet committed — so it
    # found nothing and returned without a word. A web request commits within
    # milliseconds and usually won that race; the scheduler commits once, at
    # the end of a whole tick, and lost it every time. Every expiry notice and
    # every toolbox chase since they were built was filed and never sent, and
    # a few request emails (a close, a recommendation) went the same way.
    # Held on the session and handed over by `_after_commit`; dropped on a
    # rollback, because the row they would have read no longer exists.
    db.sync_session.info.setdefault(_PENDING, []).append(record.id)
    return record


_PENDING = "ehs_mail_pending"


# ★ Review (uniops-8b), confirmed on SQLAlchemy 2.0.36: both events also fire
# for a SAVEPOINT — released, it would send before the request commits (the
# race again); rolled back, it would drop mail the request still commits. Only
# the outermost transaction decides. A message queued inside a savepoint that
# is rolled back finds no row and is not sent (`deliver`).


@event.listens_for(Session, "after_commit")
def _after_commit(session: Session) -> None:
    if session.in_nested_transaction():
        return
    for communication_id in session.info.pop(_PENDING, []):
        # Tracked rather than a bare create_task: a discarded task takes its
        # database session down with it, still holding a transaction.
        background.spawn(deliver(communication_id), name=f"ehs-mail-{communication_id}")


@event.listens_for(Session, "after_rollback")
def _after_rollback(session: Session) -> None:
    if session.in_nested_transaction():
        return
    session.info.pop(_PENDING, None)


async def deliver(communication_id: uuid.UUID) -> bool:
    """Transmit one queued message. Own session, own errors, never raises.

    Returns whether it left. Sending twice is refused by the `sent_at` check —
    the caller's transaction may be retried, and a duplicate notice about an
    injury is worse than a late one.
    """
    from app.db.session import AsyncSessionLocal

    async with AsyncSessionLocal() as db:
        record = await db.get(Communication, communication_id)
        if record is None or record.sent_at is not None:
            return False
        if record.body_purged_at is not None:
            # ★ B5 review B3: its words are gone (Q16); sending it now would
            # send an empty message under the original subject.
            return False

        smtp = _smtp(await _config(db))
        if not smtp["host"]:
            # The row stays, unsent. "We meant to tell them and could not" is a
            # fact worth keeping, and it is the one asked about afterwards.
            logger.warning("Safety mail not sent (%s): no SMTP host configured",
                           record.subject)
            record.error = "No mail server is set up (Admin → Company Settings)"
            await db.commit()
            return False

        msg = MIMEMultipart("alternative")
        msg["Subject"] = record.subject or ""
        msg["From"] = smtp["from_addr"] or record.from_addr
        msg["To"] = ", ".join(record.to_addrs or [])
        if record.cc_addrs:
            msg["Cc"] = ", ".join(record.cc_addrs)
        msg["Message-ID"] = record.message_id or make_msgid(domain="safety.uniops")
        msg.attach(MIMEText(record.body_text or "", "plain"))
        msg.attach(MIMEText(record.body_html or "", "html"))

        try:
            import aiosmtplib

            port = int(smtp["port"] or 587)
            # aiosmtplib distinguishes two TLS modes the single "use TLS"
            # toggle conflates. Forcing implicit TLS on a 587 submission server
            # yields [SSL: WRONG_VERSION_NUMBER] — this codebase has been there.
            implicit = bool(smtp["use_tls"]) and port == 465
            await aiosmtplib.send(
                msg,
                hostname=smtp["host"],
                port=port,
                username=smtp["user"] or None,
                password=smtp["password"] or None,
                use_tls=implicit,
                start_tls=bool(smtp["use_tls"]) and not implicit,
            )
        except Exception as exc:
            logger.exception("Safety mail failed: %s -> %s",
                             record.subject, record.to_addrs)
            # COM-01: the reason, on the row, for the log to show.
            record.error = (f"{type(exc).__name__}: {exc}")[:500]
            await db.commit()
            return False

        record.sent_at = datetime.now(timezone.utc)
        record.error = None
        await db.commit()
        return True


async def history(
    db: AsyncSession, *, doc_type: str, doc_id: uuid.UUID
) -> list[Communication]:
    """Everything sent about one record, oldest first."""
    return list((await db.execute(
        select(Communication)
        .where(Communication.doc_type == doc_type, Communication.doc_id == doc_id,
               Communication.is_auto_reply.is_(False))
        .order_by(Communication.created_at)
    )).scalars())


async def remind(db: AsyncSession, original: Communication, *, to: list[str],
                 by_name: str | None) -> Communication:
    """★ Round 12, COM-03: send a message again, as a reminder, to the people
    HSE picked from those it went to (Q16).

    A new row pointing at the first: what was sent stays what was sent, and
    "at most once" still holds for each row. Filed against the same record, so
    it is listed with the record's notifications. The words are the first
    message's, escaped again by `render`; nothing new is typed into it.
    """
    from app.services.day_range import ONTARIO
    when = (original.sent_at or original.created_at).astimezone(ONTARIO)
    body = (f"A reminder of a message first sent on {when:%-d %B %Y}.\n\n"
            + (original.body_text or ""))
    subject = f"Reminder: {original.subject or ''}"[:500]
    return await _file(
        db, to=to, cc=None, subject=subject, body=body,
        body_html=render(body, title=subject, link=original.link,
                         link_label=original.link_label or "Open it in Safety"),
        doc_type=original.doc_type, doc_id=original.doc_id,
        template_key=original.template_key, link=original.link,
        link_label=original.link_label, resend_of=original.id, resent_by_name=by_name)


async def purge_bodies(db: AsyncSession, *, now: datetime, days: int) -> int:
    """★ Round 12, Q16: an email's words are kept for HSE's retention period
    (Rules; 21 days unless changed), because they can carry injury details
    and what somebody wrote in feedback. Who was told, about which record,
    when and whether it left are kept — that is the audit trail.
    0 keeps the words for good."""
    from datetime import timedelta

    from sqlalchemy import update
    if days <= 0:
        return 0
    return (await db.execute(
        update(Communication)
        .where(Communication.created_at < now - timedelta(days=days),
               Communication.body_purged_at.is_(None))
        .values(body_text=None, body_html=None, body_purged_at=now))).rowcount or 0
