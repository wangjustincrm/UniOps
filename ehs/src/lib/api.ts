/**
 * Open a file the API serves, in a new tab.
 *
 * A plain link cannot carry the session header and comes back a 401, so the
 * bytes are fetched and handed to the browser as a blob. Every "open the
 * attachment" in this module goes through here — three of them were built as
 * an upload with no way back down, which is the half people actually use.
 */
/** Types a browser will render in a tab. Anything else is a download. */
const INLINE_TYPES = ['application/pdf', 'image/', 'text/']

export async function openFile(path: string, filename?: string): Promise<void> {
  const blob = await apiBlob(path)
  const url = URL.createObjectURL(blob)

  // ★ A spreadsheet is saved, not viewed. `window.open` on a blob a browser
  // cannot render leaves a blank tab behind and saves the file under the blob's
  // random uuid instead of its name — so an export arrived as
  // "a3f1c2…" with no extension. Raised in review by uniops-41.
  //
  // Judged on the blob's own type, with the filename as the fallback for a
  // server that sent none.
  const inline = INLINE_TYPES.some((t) => blob.type.startsWith(t))
    || (!blob.type && (filename ?? '').endsWith('.pdf'))
  if (!inline && filename) {
    const a = document.createElement('a')
    a.href = url
    a.download = filename
    a.click()
    setTimeout(() => URL.revokeObjectURL(url), 60_000)
    return
  }

  // ★ No `noopener` in the feature string. The spec says `window.open`
  // returns null whenever it is given, so the blocked-pop-up branch below
  // fired on every single call — every click opened the file in a tab and
  // downloaded a second copy of it. The isolation `noopener` buys is applied
  // afterwards instead, which leaves the return value meaning what it says.
  const w = window.open(url, '_blank')
  if (w) {
    w.opener = null
  } else if (filename) {
    // Genuinely blocked — hand it over as a download rather than losing it.
    const a = document.createElement('a')
    a.href = url
    a.download = filename
    a.click()
  }

  setTimeout(() => URL.revokeObjectURL(url), 60_000)
}

/**
 * Opening a file from a button, with somewhere for the failure to go.
 *
 * `openFile` rejects on a 403 or a 404 like any other request, and an
 * `onClick` that calls it swallows that — the button was pressed, nothing
 * happened, and nothing said why. This keeps the message so a page can render
 * it beside whatever was clicked.
 */
export function useFileOpener() {
  const [error, setError] = useState<string | null>(null)
  const [busy, setBusy] = useState(false)

  const open = async (path: string, filename?: string) => {
    if (busy) return
    setBusy(true)
    setError(null)
    try {
      await openFile(path, filename)
    } catch (e) {
      setError(e instanceof ApiError ? e.message : 'The file could not be opened.')
    } finally {
      setBusy(false)
    }
  }

  return { open, error, busy }
}
